/// One query golden under `tests/conformance/graph/queries/`.
fn query_golden(name: &str) -> PathBuf {
    conformance_fixture("tests/conformance/graph/queries").join(name)
}

/// The committed golden's bytes; under `REX_UPDATE_FIXTURES` the freshly
/// emitted answer is written first (the artifact-golden discipline).
fn query_golden_text(name: &str, actual: &str) -> String {
    let path = query_golden(name);
    if std::env::var("REX_UPDATE_FIXTURES").is_ok() {
        std::fs::write(&path, actual).expect("write query golden");
        eprintln!("updated {}", path.display());
        return actual.to_string();
    }
    std::fs::read_to_string(&path)
        .expect("read query golden — regenerate with REX_UPDATE_FIXTURES=1")
}

/// Runs `rexlang graph query <arguments>`.
fn run_query(arguments: &[&str]) -> Output {
    rexlang()
        .arg("graph")
        .arg("query")
        .args(arguments)
        .output()
        .expect("run rexlang graph query")
}

/// Runs one query against the committed examples artifact.
fn query_examples(arguments: &[&str]) -> Output {
    let graph = graph_golden();
    let graph = graph.to_str().expect("utf-8 graph path");
    let mut all = vec![graph];
    all.extend_from_slice(arguments);
    run_query(&all)
}

fn stdout(output: &Output) -> String {
    String::from_utf8_lossy(&output.stdout).into_owned()
}

fn parsed(output: &Output) -> serde_json::Value {
    assert!(
        output.status.success(),
        "query must succeed: {}",
        stderr(output)
    );
    serde_json::from_str(&stdout(output)).expect("the answer is one JSON envelope")
}

/// `node` prints the committed envelope: the node's identity fields plus its
/// incident edges grouped by direction.
#[test]
fn query_node_prints_the_golden() {
    let output = query_examples(&["node", CAPABILITY, "--edges", "--pretty"]);
    let actual = stdout(&output);
    assert_eq!(
        actual,
        query_golden_text("examples.node.capability-raise-refund.json", &actual)
    );
    let envelope = parsed(&query_examples(&["node", CAPABILITY, "--edges"]));
    assert_eq!(envelope["formatVersion"], 1);
    assert_eq!(envelope["query"], "node");
    assert_eq!(envelope["resolved"], CAPABILITY);
    assert_eq!(envelope["results"][0]["id"], CAPABILITY);
    assert_eq!(envelope["results"][0]["file"], "support.actor");
    assert_eq!(envelope["results"][0]["application"], "cli.ifml");
    let out = envelope["edges"]["out"].as_array().expect("out edges");
    let incoming = envelope["edges"]["in"].as_array().expect("in edges");
    assert!(!out.is_empty() && !incoming.is_empty(), "both directions");
    assert!(out.iter().all(|edge| edge["from"] == CAPABILITY));
    assert!(incoming.iter().all(|edge| edge["to"] == CAPABILITY));
    // Without `--edges` the group is absent (the empty-artifact discipline).
    let plain = parsed(&query_examples(&["node", CAPABILITY]));
    assert!(plain.get("edges").is_none());
}

/// `list` filters compose and the result is always sorted by id.
#[test]
fn query_list_filters_by_kind_file_application() {
    let artifact = GraphModel::from_json(
        &std::fs::read_to_string(graph_golden()).expect("read the examples graph golden"),
    )
    .expect("versioned graph");
    let all = parsed(&query_examples(&["list"]));
    let results = all["results"].as_array().expect("results");
    assert_eq!(results.len(), artifact.nodes.len(), "no filter, every node");
    let ids: Vec<&str> = results
        .iter()
        .map(|node| node["id"].as_str().expect("id"))
        .collect();
    let mut sorted = ids.clone();
    sorted.sort();
    assert_eq!(ids, sorted, "list sorts by id");
    assert!(results.iter().all(|node| node.get("depth").is_none()));

    let components = parsed(&query_examples(&["list", "--kind", "deployComponent"]));
    let components = components["results"].as_array().expect("results");
    assert!(!components.is_empty());
    assert!(components
        .iter()
        .all(|node| node["kind"] == "deployComponent"));
    assert_eq!(all["results"][0]["kind"], "action", "kinds are lowercase");

    let designs = parsed(&query_examples(&["list", "--file", "support.ddd"]));
    let designs = designs["results"].as_array().expect("results");
    assert!(!designs.is_empty());
    assert!(designs.iter().all(|node| node["file"] == "support.ddd"));

    let capabilities = parsed(&query_examples(&[
        "list",
        "--application",
        "cli.ifml",
        "--kind",
        "capability",
    ]));
    assert_eq!(capabilities["kind"], "capability");
    assert_eq!(capabilities["application"], "cli.ifml");
    let capabilities = capabilities["results"].as_array().expect("results");
    assert!(!capabilities.is_empty());
    assert!(capabilities
        .iter()
        .all(|node| node["kind"] == "capability" && node["application"] == "cli.ifml"));
}

