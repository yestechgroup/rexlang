#[test]
fn graph_paths_are_root_relative() {
    let out = scratch_dir().join("examples.graph.json");
    let _ = run_graph(&[
        examples_dir().to_str().expect("utf-8 examples path"),
        "-o",
        out.to_str().expect("utf-8 output path"),
    ]);
    let json = std::fs::read_to_string(&out).expect("read graph output");
    // Under `REX_UPDATE_FIXTURES` this keeps the golden in step without
    // racing the other golden tests; otherwise it verifies the artifact
    // against the committed bytes.
    let golden = golden_of(&json);
    assert_eq!(json, golden);
    let graph = GraphModel::from_json(&json).expect("versioned graph");
    assert!(
        graph
            .applications
            .iter()
            .any(|application| application.files.iter().any(|file| file == "support.mox")),
        "support.mox is a member of the examples tree"
    );
    assert!(
        json.contains("\"file\": \"support.mox\""),
        "node attribution is the root-relative display path"
    );
    let root = workspace_root().display().to_string();
    assert!(
        !json.contains(&root),
        "the artifact must not carry the workspace root"
    );
    assert!(
        !json.contains('\\'),
        "display paths are POSIX: no backslashes"
    );
}

#[test]
fn graph_still_writes_when_a_file_fails() {
    // One broken file: the command renders its diagnostics, writes the
    // graph over the compiling subset, and exits 1 (the `build` precedent).
    let good = write_source("good.mox", GOOD);
    let broken = write_source("broken.mox", BAD);
    let directory = good.parent().expect("scratch dir").to_path_buf();
    let out = directory.join("failed.graph.json");
    let output = run_graph(&[
        directory.to_str().expect("utf-8 scratch path"),
        "-o",
        out.to_str().expect("utf-8 output path"),
    ]);
    assert_eq!(output.status.code(), Some(1));
    let rendered = stderr(&output);
    assert!(
        rendered.contains(broken.to_str().expect("utf-8 broken path")),
        "the failing file must be named: {rendered}"
    );
    assert!(
        rendered.contains("1 of 2 files failed"),
        "the batch summary counts the failure: {rendered}"
    );
    let json = std::fs::read_to_string(&out).expect("the artifact is still written");
    let graph = GraphModel::from_json(&json).expect("versioned graph");
    assert!(
        graph.nodes.iter().any(|node| node.kind == "class"
            && node.name == "demo.Book"
            && node.file == "good.mox"),
        "the compiling subset still emits: {json}"
    );
}

