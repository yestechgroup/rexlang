/// `--fail-on-findings` exits `1` only when a **definite** finding exists;
/// the envelope still prints, and an uncertain (`unknown`) answer never
/// fails the gate.
#[test]
fn query_fail_on_findings_exits_1_only_with_findings() {
    let cases: [(&[&str], i32); 7] = [
        // A declared, clean pair: no finding.
        (&["separation-of-duty"], 0),
        // The undeclared pair: the manager holds both sides.
        (
            &[
                "separation-of-duty",
                "--pair",
                "App.RaiseRefund",
                "App.ApproveRefund",
            ],
            1,
        ),
        // The manager lost the agent's UpdateTicket.
        (&["monotonicity", "--actor", "App.Manager"], 1),
        // One dead capability.
        (&["dead-capabilities"], 1),
        // The target is reached.
        (
            &[
                "reachability",
                "--from-actor",
                "App.Agent",
                "--to",
                "Note.body",
            ],
            0,
        ),
        // The target is not reached.
        (
            &[
                "reachability",
                "--from-actor",
                "App.Agent",
                "--to",
                "Invoice.amount",
            ],
            1,
        ),
        // The other application's capabilities are `unknown`, never `dead`.
        (&["dead-capabilities", "--session", "agent"], 1),
    ];
    for (arguments, expected) in cases {
        let plain = query_fixture(arguments);
        assert!(plain.status.success(), "{arguments:?}: {}", stderr(&plain));
        let gated = query_fixture(&[arguments, &["--fail-on-findings"]].concat());
        assert_eq!(
            gated.status.code(),
            Some(expected),
            "{arguments:?}: {}",
            stderr(&gated)
        );
        assert_eq!(
            stdout(&plain),
            stdout(&gated),
            "the answer prints either way"
        );
    }
}
