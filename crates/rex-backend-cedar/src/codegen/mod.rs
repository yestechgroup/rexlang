//! The Cedar emitter: per `actors` block, one Cedar policy set
//! (`<Block>.cedar`) and one Cedar JSON schema (`<Block>.cedarschema.json`).
//!
//! Mapping contract (each item pinned by a test here or in `tests/`):
//!
//! - **Schema**: namespace = block name. One entity type per actor; an
//!   actor's `extends` becomes `memberOfTypes` pointing at the parent's
//!   fully-qualified type (roots carry no key). One entity type per
//!   capability class, shaped as a `Record` of the class's primitive-typed
//!   stored attributes (`String`/`char` → `String`, `int`/`long`/`short`/
//!   `byte` → `Long`, `float`/`double` → `Double`, `boolean` → `Boolean`).
//!   Refs, containments, enums, datatypes, and derived features are not
//!   attributes. One action per capability; `principalTypes` are the actors
//!   whose authority reaches the action — a direct grant entry (permit or
//!   forbid), a grant inherited along the `extends` chain, or a delegation
//!   binding addressed to the actor or an ancestor (rexlang#132) — in actor
//!   declaration order, empty when none does.
//! - **Policies**: one policy per effect entry per actor holding the
//!   entry's authority — the granted actor plus every `extends` descendant
//!   (Cedar's `is` is an exact-type match, so inherited authority must be
//!   addressed by type) — IR entry order, declaration order within an
//!   entry, fully parenthesized `when { ... }` conditions over
//!   `resource.<feature>`.
//!   Conditions are restricted to a decidable subset: literals, bare names
//!   (primitive attributes only), unary/binary operators, parentheses.
//!   Anything else (`let`, `if`, lambdas, collection algebra, `?.`, `?:`,
//!   `null`, list literals, operation calls) is a generate-time error naming
//!   the capability and the construct — Cedar has no null, so silent
//!   mismatches are refused loudly. `cedar { ... }` entries are spliced
//!   verbatim (the author owns that text). `never_both` is not expressible
//!   in Cedar and degrades to an evidence comment line; the driver enforces
//!   it, not the policy set. Delegations degrade the same way: one evidence
//!   comment line each (name, `from -> to`, permit-entry count, then
//!   ` purpose: <P>` when the delegation declares a purpose), after the
//!   `never_both` comments — policies and schema are untouched.
//!
//! Output is deterministic: the schema JSON is emitted with object keys in
//! canonical alphabetical order (immune to serde_json's `preserve_order`
//! feature, which some build graphs enable), and the policy text follows IR
//! order. Policy files end with exactly one newline.

